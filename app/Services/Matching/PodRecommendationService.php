<?php

namespace App\Services\Matching;

use App\Contracts\HasAccountType;
use App\Contracts\PodMatchingAlgorithm;
use App\Enums\Matching\MatchStatus;
use App\Enums\Pod\PodStatus;
use App\Enums\PodUser\State;
use App\Models\Pod;
use App\Models\PodMatch;
use App\Models\PodRecommendationDismissal;
use App\Models\PodUser;
use App\Models\User;
use App\Services\Profile\ProfileCompletionService;
use Illuminate\Database\Eloquent\Collection as EloquentCollection;
use Illuminate\Pagination\LengthAwarePaginator;
use Illuminate\Support\Collection;

/**
 * Read model of an employee's POD recommendations (UNA-017). Reads persisted matches only: it
 * never scores, dispatches jobs or changes memberships.
 *
 * A POD is recommended to the employee when one of their stored matches:
 *  - was generated by the active algorithm key AND version (UNA-016; older results are hidden
 *    until regenerated),
 *  - is qualified by MatchQualification::of() (eligible, score >= the POD's current threshold,
 *    active requirement, published POD),
 *  - belongs to a POD the employee has not dismissed and that has not excluded them from matching (UNA-018),
 *  - belongs to a POD where the employee has no membership, or only an open applicant one
 *    (matched / pending_business_approval, shown as a status instead of "Apply"); active,
 *    suspended, rejected and removed memberships are left to manual discovery.
 *
 * Several requirements of one POD collapse to its best match (DeterministicPodMatchingService::rank()).
 * PODs are ranked by score desc, then generation time desc, then POD id asc; pagination is per POD.
 */
class PodRecommendationService
{
    public function __construct(
        private PodMatchPresenter $presenter,
        private ProfileCompletionService $completion,
    ) {
    }

    /** Only regular employee accounts have recommendations. */
    public function canView(?HasAccountType $account): bool
    {
        return $account instanceof User && $account->isRegularUser() && $account->isEmployee();
    }

    /** @return LengthAwarePaginator<PodRecommendation> */
    public function paginate(User $employee, int $page = 1, ?int $perPage = null): LengthAwarePaginator
    {
        $perPage ??= max(1, (int) config('pod_matching.recommendations.per_page', 9));
        $ranked = $this->rankedMatches($employee);
        $slice = new EloquentCollection($ranked->forPage($page, $perPage)->values()->all());

        // Card relations for this page only (requirement.pod is already loaded by rankedMatches()).
        $slice->loadMissing(['reasons', 'requirement.jobTitle', 'requirement.pod', 'pod.creator.workspacesOwner']);
        $states = $this->membershipStates($employee, $slice->pluck('pod_id')->all());
        $items = $slice->map(fn (PodMatch $match) => $this->recommendation($match, $states[$match->pod_id] ?? null));

        return new LengthAwarePaginator($items, $ranked->count(), $perPage, $page, [
            'path' => route('pod-recommendations.index'),
            'pageName' => 'page',
        ]);
    }

    /**
     * Best qualified match per recommended POD, ranked. Light models: requirement and pod only.
     *
     * @return Collection<int, PodMatch>
     */
    public function rankedMatches(User $employee): Collection
    {
        $algorithm = app(PodMatchingAlgorithm::class);

        $candidates = PodMatch::query()
            ->where('pod_matches.user_id', $employee->id)
            ->where('pod_matches.status', MatchStatus::ELIGIBLE->value)
            ->where('pod_matches.algorithm', $algorithm->key())
            ->where('pod_matches.scoring_version', $algorithm->version())
            ->whereHas('pod', fn ($q) => $q->where('status', PodStatus::PUBLISHED->value))
            ->whereHas('requirement', fn ($q) => $q->where('is_active', true))
            ->whereNotExists(fn ($q) => $q->selectRaw('1')->from('pod_recommendation_dismissals as prd')
                ->whereColumn('prd.pod_id', 'pod_matches.pod_id')->where('prd.user_id', $employee->id))
            // UNA-018: a POD that excluded the employee from matching is not recommended.
            ->whereNotExists(fn ($q) => $q->selectRaw('1')->from('pod_matching_exclusions as pme')
                ->whereColumn('pme.pod_id', 'pod_matches.pod_id')->where('pme.user_id', $employee->id))
            ->with(['requirement', 'pod'])
            ->get();

        $states = $this->membershipStates($employee, $candidates->pluck('pod_id')->unique()->all());

        return $candidates
            ->filter(fn (PodMatch $m) => MatchQualification::of($m, $m->requirement, $m->pod)->qualified)
            ->filter(fn (PodMatch $m) => !isset($states[$m->pod_id]) || in_array($states[$m->pod_id], State::applicants(), true))
            ->groupBy('pod_id')
            ->map(fn ($matches) => $matches->sort(fn ($a, $b) => DeterministicPodMatchingService::rank($a) <=> DeterministicPodMatchingService::rank($b))->first())
            ->sort(fn (PodMatch $a, PodMatch $b) => [
                -MatchQualification::hundredths($a->score), -$a->evaluated_at->getTimestamp(), (int) $a->pod_id,
            ] <=> [
                -MatchQualification::hundredths($b->score), -$b->evaluated_at->getTimestamp(), (int) $b->pod_id,
            ])
            ->values();
    }

    /**
     * Dashboard metrics that the stored data supports exactly.
     *
     * @return array{count:int, top_score:?string, strong:int, strong_score:int, profile_completion:int}
     */
    public function summary(User $employee, ?Collection $ranked = null): array
    {
        $ranked ??= $this->rankedMatches($employee);
        $strongScore = (int) config('pod_matching.recommendations.strong_score', 80);

        return [
            'count' => $ranked->count(),
            'top_score' => $ranked->first()?->score !== null ? (string) $ranked->first()->score : null,
            'strong' => $ranked->filter(fn (PodMatch $m) => MatchQualification::hundredths($m->score) >= $strongScore * 100)->count(),
            'strong_score' => $strongScore,
            'profile_completion' => $this->completion->percentage($employee),
        ];
    }

    /**
     * Why the list is empty, as far as the stored data tells: 'preparing' when no result of the
     * active algorithm exists for the employee yet while published PODs are open to matching
     * (generation is queued, UNA-016); otherwise 'none'.
     */
    public function emptyReason(User $employee): string
    {
        $algorithm = app(PodMatchingAlgorithm::class);
        $hasCurrentResults = PodMatch::query()->where('user_id', $employee->id)
            ->where('algorithm', $algorithm->key())->where('scoring_version', $algorithm->version())->exists();
        $hasOpenPods = Pod::published()->whereHas('workerRequirements', fn ($q) => $q->where('is_active', true))->exists();

        return !$hasCurrentResults && $hasOpenPods ? 'preparing' : 'none';
    }

    // ------------------------------------------------------------------ internals

    /** @return array<int, State> pod_id => membership state of the employee (removed rows included) */
    private function membershipStates(User $employee, array $podIds): array
    {
        if ($podIds === []) {
            return [];
        }

        return PodUser::query()->where('user_id', $employee->id)->whereIn('pod_id', $podIds)->get(['pod_id', 'state'])
            ->mapWithKeys(fn (PodUser $m) => [(int) $m->pod_id => $m->state])->all();
    }

    private function recommendation(PodMatch $match, ?State $state): PodRecommendation
    {
        $presented = $this->presenter->present($match);
        $requirement = $match->requirement;
        $creator = $match->pod->creator;

        return new PodRecommendation(
            pod: $match->pod,
            match: $match,
            presented: $presented,
            highlights: $this->presenter->topHighlights($presented['criteria']),
            details: $this->details($requirement),
            companyName: $creator?->workspacesOwner->first(fn ($w) => trim((string) $w->company) !== '')?->company ?? $creator?->name,
            roleTitle: $requirement->jobTitle?->title,
            membershipState: $state,
        );
    }

    /** @return array<string, string> configured requirement metadata, translated */
    private function details($requirement): array
    {
        $details = [];
        if ($requirement->preferred_work_mode) {
            $details['work_mode'] = $requirement->preferred_work_mode->label();
        }
        if ($requirement->preferred_engagement_type) {
            $details['engagement'] = $requirement->preferred_engagement_type->label();
        }
        $place = trim((string) $requirement->location) !== '' ? trim((string) $requirement->location) : $requirement->timezone;
        if ($place) {
            $details['location'] = $place;
        }
        if ($requirement->project_type) {
            $details['project_type'] = $requirement->project_type->label();
        }

        return $details;
    }
}
